// Regenerates src/abi.ts from the Foundry build output. Run after `forge build`.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..", "contract", "out");
const pick = (name) => JSON.parse(readFileSync(join(root, `${name}.sol`, `${name}.json`), "utf8"));

const vault = pick("EuthynaVault");
const factory = pick("EuthynaFactory");
const out = `// Generated by scripts/gen-abi.mjs from contract/out. Do not edit by hand.
export const vaultAbi = ${JSON.stringify(vault.abi, null, 2)} as const;

export const factoryAbi = ${JSON.stringify(factory.abi, null, 2)} as const;

export const factoryBytecode = "${factory.bytecode.object}" as const;
`;
writeFileSync(join(dirname(fileURLToPath(import.meta.url)), "..", "src", "abi.ts"), out);
console.log("wrote src/abi.ts");
