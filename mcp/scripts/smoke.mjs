import { Client } from "@modelcontextprotocol/sdk/client/index.js";
import { StdioClientTransport } from "@modelcontextprotocol/sdk/client/stdio.js";
// End-to-end check: start the server over stdio and call every tool, resource and prompt.
const client = new Client({ name: "euthyna-mcp-smoke", version: "1.0.0" });
await client.connect(new StdioClientTransport({ command: "node", args: ["dist/index.js"] }));
const tools = await client.listTools();
console.log("TOOLS (" + tools.tools.length + "):", tools.tools.map(t => t.name).join(", "));
console.log("ALL READ-ONLY:", tools.tools.every(t => t.annotations?.readOnlyHint === true));
const res = await client.listResources(); const tpl = await client.listResourceTemplates(); const pr = await client.listPrompts();
console.log("RESOURCES:", res.resources.map(r => r.uri).join(", "), "| TEMPLATES:", tpl.resourceTemplates.map(r => r.uriTemplate).join(", "));
console.log("PROMPTS:", pr.prompts.map(p => p.name).join(", "));
const call = async (name, args = {}) => { const r = await client.callTool({ name, arguments: args }); const t = r.content[0].text; console.log(`\n### ${name}${r.isError ? " (ERROR)" : ""}\n` + t.split("\n")[0]); return t; };
await call("get_public_stats");
await call("list_businesses");
await call("get_vault");
await call("list_bills", { status: "PAID" });
await call("list_payees");
await call("list_commitments");
await call("get_trust_history");
await call("list_decisions", { limit: 3 });
await call("get_decision", { id: "f30f2177-a816-48b1-a1af-1597c3303c2e" });
await call("verify_decision", { id: "f30f2177-a816-48b1-a1af-1597c3303c2e" });
await call("build_settle_tx", { commitmentId: 1 });
await call("build_settle_tx", { vault: "0x4a08A58be01B5311D36EF4b042AA83BF738cF2b5", commitmentId: 99 });
await call("build_register_bill_tx", { payee: "0x6b9d413446ca93bec8d3f78745b1140a92eac964", amountUsdc: "5", dueAt: "2026-12-01T12:00:00Z", invoiceNumber: "TEST-1" });
await call("get_vault", { vault: "not-an-address" });
const doc = await client.readResource({ uri: "euthyna://docs/how-it-works" }); console.log("\n### resource how-it-works:", doc.contents[0].text.split("\n")[0]);
const v = await client.readResource({ uri: "euthyna://vault/0x0767f13610b794f1de85CEe78728114df1Ffa23d" }); console.log("### resource vault: liquid", JSON.parse(v.contents[0].text).liquid);
const p = await client.getPrompt({ name: "audit_decision", arguments: { decisionId: "abc" } }); console.log("### prompt audit_decision:", p.messages[0].content.text.slice(0, 60) + "…");
await client.close();
